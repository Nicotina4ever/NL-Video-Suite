const {navigate}=require('./navigation.cjs');
const {chromium}=require('playwright');
const {spawn,execFileSync}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
const net=require('node:net');
const http=require('node:http');
const devRoot=path.resolve(__dirname,'..');
const root=path.basename(devRoot)==='sviluppo'?path.dirname(devRoot):devRoot;
async function main(){
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'nl-ui-test-'));
 const listener=net.createServer();await new Promise(resolve=>listener.listen(0,'127.0.0.1',resolve));const port=listener.address().port;await new Promise(resolve=>listener.close(resolve));
 const source=path.join(directory,'studio.mp4');
 execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','testsrc2=s=640x360:r=30:d=2','-c:v','libx264','-pix_fmt','yuv420p',source],{windowsHide:true});
 const executable=process.argv[2]?path.resolve(process.argv[2]):path.join(root,'app','nl-video-suite.exe');
 const fake=http.createServer((req,res)=>{res.setHeader('Content-Type','application/json');res.end(JSON.stringify(req.url==='/object_info'?{
  EmptyLTXVLatentVideo:{input:{required:{width:['INT']}},output:['LATENT']},
  LTXVSeparateAVLatent:{input:{required:{av_latent:['LATENT']}},output:['LATENT','LATENT']},
  SaveVideo:{input:{required:{samples:['LATENT']}},output_node:true,output:[]}
 }:{models:[{name:'synthetic-test-model'},{name:'modello-locale-test'}]}));});
 await new Promise(resolve=>fake.listen(0,'127.0.0.1',resolve));
 const data=path.join(directory,'data');fs.mkdirSync(data);const fakeUrl=`http://127.0.0.1:${fake.address().port}`;
 fs.writeFileSync(path.join(data,'settings.json'),JSON.stringify({comfy_url:fakeUrl,ollama_url:fakeUrl,legacy_sources:{}}));
 const server=spawn(executable,['--port',String(port),'--data-dir',path.join(directory,'data')],{windowsHide:true,stdio:'ignore'});
 let browser;
 try{
  const base=`http://127.0.0.1:${port}`;
  for(let i=0;i<100;i++){try{const r=await fetch(base+'/api/projects');if(r.ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1550,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);
  await page.locator('#new-project').click();
  await page.locator('#title').fill('Studio di prova · montaggio');
  await page.locator('#create-form button').first().click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Progetto creato.');
  await page.locator('#asset-path').fill(source);
  await page.locator('#import-form button').click();
  await page.locator('[data-add]').first().waitFor({timeout:20000});
  await page.locator('[data-preview]').first().click();
  await page.locator('[data-add]').first().click();
  await page.locator('#numeric-editor summary').click();
  await page.locator('.clip').waitFor();
  await page.locator('[data-field="start_ms"]').fill('0.5');
  await page.locator('[data-field="trim_in_ms"]').fill('0.5');
  await page.locator('[data-field="duration_ms"]').fill('1');
  await page.locator('[data-clip-action="save"]').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Timeline salvata.');
  await page.locator('#undo').click();
  await page.waitForFunction(()=>document.querySelector('[data-field="start_ms"]').value==='0');
  await page.locator('#redo').click();
  await page.waitForFunction(()=>document.querySelector('[data-field="start_ms"]').value==='0.5');
  await page.locator('#render').click();
  await page.locator('[data-export]').waitFor({timeout:25000});
  await page.locator('#upload-file').setInputFiles(source);
  await page.locator('#upload-form button').click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-add]').length===2);
  fs.mkdirSync(path.join(__dirname,'artifacts'),{recursive:true});
  await page.screenshot({path:path.join(__dirname,'artifacts','studio-desktop.png'),fullPage:true});
  await navigate(page,'pipeline');
  await page.locator('details.flow-legacy summary').first().click();
  await page.locator('#transcript-json').evaluate(el=>el.closest('details').open=true);
  await page.locator('#transcript-json').fill(JSON.stringify({segments:[{start:.1,end:.8,text:'Trascrizione sintetica verificata'}]}));
  await page.locator('#transcript-form button').click();
  await page.locator('#transcripts summary').waitFor();
  await page.reload();
  await page.locator('#numeric-editor summary').click();
  await page.locator('.clip').waitFor();
  assert.equal(await page.locator('[data-field="start_ms"]').inputValue(),'0.5');
  const workflowDirectory=path.join(directory,'workflows');fs.mkdirSync(workflowDirectory);
  const workflowPath=path.join(workflowDirectory,'broken-ltx.json');
  const graph=JSON.stringify({a:{class_type:'EmptyLTXVLatentVideo',inputs:{width:1280}},b:{class_type:'LTXVSeparateAVLatent',inputs:{av_latent:['a',0]}},c:{class_type:'SaveVideo',inputs:{samples:['b',0]}}});
  fs.writeFileSync(workflowPath,graph);
  const scan=await (await page.request.post(base+'/api/workflows/scan',{data:{roots:[workflowDirectory]}})).json();
  for(let i=0;i<100;i++){const job=await (await page.request.get(base+'/api/jobs/'+scan.id)).json();if(job.status==='succeeded')break;await page.waitForTimeout(50);}
  await navigate(page,'workflows');
  await page.waitForFunction(()=>[...document.querySelector('#workflow-list').options].some(o=>o.textContent==='broken-ltx'));
  const workflowId=await page.locator('#workflow-list option').filter({hasText:'broken-ltx'}).first().getAttribute('value');
  await page.locator('#workflow-list').selectOption(workflowId);
  await page.locator('#diagnose-workflow').click();
  await page.locator('[data-repair]').waitFor();
  await page.locator('#repair-workflow').click();
  await page.waitForFunction(()=>document.querySelector('#workflow-diagnosis').textContent.includes('Preflight tecnico superato'));
  assert.equal(fs.readFileSync(workflowPath,'utf8'),graph);
  await navigate(page,'graphics');
  assert(await page.locator('#review-graphics').isChecked());
  assert.equal(await page.locator('#graphics-workflow').inputValue(),'');
  const direction='Documentario botanico. Verde salvia e luce naturale, nessun viola imposto.';
  await page.locator('#creative-brief').fill(direction);
  await page.locator('#save-creative-brief').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Direzione visiva salvata solo in questo progetto.');
  await page.reload();
  await navigate(page,'graphics');
  await page.waitForFunction(()=>document.querySelector('#creative-brief').value.includes('Documentario botanico'));
  assert.equal(await page.locator('#creative-brief').inputValue(),direction);
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--brand-violet').trim().toLowerCase()),'#7531fe');
  await page.locator('#new-project').click();
  await page.locator('#title').fill('Progetto con stile indipendente');
  await page.locator('#create-form button').first().click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Progetto creato.');
  assert.equal(await page.locator('#creative-brief').inputValue(),'');
  await page.locator('#projects').selectOption({label:'Studio di prova · montaggio'});
  await page.waitForFunction(()=>document.querySelector('#creative-brief').value.includes('Documentario botanico'));
  await navigate(page,'system');
  await page.locator('.status-card').first().waitFor();
  assert.equal(await page.locator('.status-card').count(),6);
  assert.equal(await page.locator('#legacy-import-panel').count(),0,'legacy import UI was intentionally retired');
  assert(!await page.locator('#tab-system').innerText().then(t=>t.includes('Provenienza delle integrazioni')));
  await page.locator('#refresh-models').click();
  await page.waitForFunction(()=>[...document.querySelector('#llm-model').options].some(o=>o.value==='modello-locale-test'));
  await page.locator('#llm-model').selectOption('modello-locale-test');
  await page.locator('#settings-form button').first().click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Impostazioni applicate. Non serve riavviare la suite.');
  assert.equal((await (await page.request.get(base+'/api/settings')).json()).llm_model,'modello-locale-test');
  await page.reload();
  await navigate(page,'system');
  await page.waitForFunction(()=>document.querySelector('#llm-model').value==='modello-locale-test');
  await page.screenshot({path:path.join(__dirname,'artifacts','sistema-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'system mobile overflow');
  await page.screenshot({path:path.join(__dirname,'artifacts','sistema-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1550,height:1000});
  await navigate(page,'studio');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(__dirname,'artifacts','studio-mobile.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS browser: editor/export, doctor/review, logo palette, independent project direction, live system settings, desktop/mobile, no JS exceptions');
 }finally{
  if(browser)await browser.close();
  server.kill();await new Promise(resolve=>server.once('exit',resolve));
  await new Promise(resolve=>fake.close(resolve));
  fs.rmSync(directory,{recursive:true,force:true,maxRetries:10,retryDelay:100});
 }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
